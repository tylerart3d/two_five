import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'data/shared/official_histories');
const manifestPath = path.join(base, 'IMPORT_MANIFEST.md');
const digest = (bytes, algorithm = 'sha256') => createHash(algorithm).update(bytes).digest('hex');
async function manifest() {
  try { return JSON.parse((await fs.readFile(manifestPath, 'utf8')).match(/```json\n([\s\S]*?)\n```/)[1]); }
  catch (error) { if (error.code === 'ENOENT') return { version: 1, files: [] }; throw error; }
}
function destination(relative) {
  const resolved = path.resolve(root, relative);
  if (!resolved.startsWith(base + path.sep) || !relative.includes('/_files/')) throw new Error('Invalid external destination');
  return resolved;
}
export async function checkExternalResearch() {
  const saved = await manifest();
  for (const file of saved.files) {
    const bytes = await fs.readFile(destination(file.destination));
    if (bytes.length !== file.bytes || digest(bytes) !== file.sha256) throw new Error(`External integrity mismatch: ${file.destination}`);
  }
  console.log(`Verified ${saved.files.length} external source files against SHA-256 manifest.`);
}
async function run() {
  if (process.argv.includes('--check')) return checkExternalResearch();
  const specPath = process.argv[2];
  if (!specPath) throw new Error('Usage: node scripts/import-external-research.mjs <source-spec.md> or --check');
  const spec = JSON.parse((await fs.readFile(specPath, 'utf8')).match(/```json\n([\s\S]*?)\n```/)[1]);
  const saved = await manifest();
  for (const file of spec.files) {
    const dest = destination(file.destination);
    const old = saved.files.find(item => item.destination === file.destination);
    if (old) {
      if (old.url !== file.url) throw new Error('Source URL changed for existing evidence');
      const bytes = await fs.readFile(dest);
      if (digest(bytes) !== old.sha256) throw new Error(`Modified evidence: ${file.destination}`);
      continue;
    }
    const response = await fetch(file.url, { signal: AbortSignal.timeout(120000) });
    if (!response.ok) throw new Error(`${response.status}: ${file.url}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (!bytes.length) throw new Error('Empty source');
    if (file.bytes && bytes.length !== file.bytes) throw new Error('Source size mismatch');
    if (file.md5 && digest(bytes, 'md5') !== file.md5) throw new Error('Archive checksum mismatch');
    if (file.kind === 'pdf' && !bytes.subarray(0, 5).equals(Buffer.from('%PDF-'))) throw new Error('Expected PDF');
    if (file.kind !== 'pdf' && /<!doctype html|<html/i.test(bytes.subarray(0, 300).toString())) throw new Error('Unexpected HTML response');
    await fs.mkdir(path.dirname(dest), { recursive: true });
    try { await fs.writeFile(dest, bytes, { flag: 'wx' }); }
    catch (error) {
      if (error.code !== 'EEXIST' || digest(await fs.readFile(dest)) !== digest(bytes)) throw error;
    }
    saved.files.push({ ...file, source_id: spec.source_id, bytes: bytes.length, sha256: digest(bytes), retrieved_at: new Date().toISOString(), resolved_url: response.url });
    await fs.mkdir(base, { recursive: true });
    await fs.writeFile(manifestPath, '# External source import manifest\n\nGenerated by scripts/import-external-research.mjs. Source bytes remain local-only.\n\n```json\n' + JSON.stringify(saved, null, 2) + '\n```\n');
    console.log(`Imported ${file.destination}: ${bytes.length} bytes`);
  }
  await checkExternalResearch();
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await run();
